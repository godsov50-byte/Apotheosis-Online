"use strict";
const assert=require("node:assert/strict");
const r=require("../../geography/consistency-registry");
assert.equal(r.identityKey("houston-roads-v1","feature/000184"),r.identityKey("houston-roads-v1","feature/000184"));
assert.notEqual(r.identityKey("houston-roads-v1","184"),r.identityKey("houston-roads-v1","185"));
assert.equal(r.stableStringify({z:1,nested:{b:2,a:1},a:3}),'{"a":3,"nested":{"a":1,"b":2},"z":1}');
assert.equal(r.coordinateKey({lat:29.760193,lon:-95.369361},"houston",1),r.coordinateKey({lon:-95.369361,lat:29.760193},"houston",1));
const s=r.createRegistry(),k=r.identityKey("dataset-a","road-17");
s.register({identityKey:k,objectId:"ao-road-17",revisionId:"rev-1"});
assert.equal(s.retrieve(k).objectId,"ao-road-17");
assert.equal(s.retrieveByObjectId("ao-road-17").identityKey,k);
assert.throws(()=>s.register({identityKey:k,objectId:"ao-road-18"}),/Identity collision/);
const c=r.createCorrectionProposal({objectId:"ao-road-17",targetRevision:"rev-1",propertyPath:"geometry",observedValue:{x:1},proposedValue:{x:2},evidence:[{source:"survey",id:"p4"}]});
assert.equal(c.status,"pending_review");assert.equal(c.autoApplied,false);
assert.throws(()=>r.createCorrectionProposal({objectId:"x",targetRevision:"r1",propertyPath:"geometry",evidence:[]}),/requires evidence/);
const m=r.createGenerationManifest({artifactKind:"portrait",sourceObjectIds:["char-2","char-1"],sourceRevisionIds:["r2","r1"],ruleVersion:"visual-v3",promptTemplateVersion:"portrait-v2",seed:"seed-42"});
assert.deepEqual(m.sourceObjectIds,["char-1","char-2"]);assert.deepEqual(m.sourceRevisionIds,["r1","r2"]);
assert.throws(()=>r.createGenerationManifest({artifactKind:"lore",sourceObjectIds:[],ruleVersion:"r1",promptTemplateVersion:"p1",seed:"1"}),/requires authoritative/);
console.log("AO deterministic registry tests passed");
